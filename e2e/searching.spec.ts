import { expect, test, type Page } from '@playwright/test'

async function prepare(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Searching', exact: true }).click()
  const size = page.getByRole('slider', { name: /Array size/ })
  await size.focus(); await size.press('Home')
  await page.getByText('Inspect array values', { exact: false }).click()
  const speed = page.getByRole('slider', { name: /Speed/ })
  await speed.focus(); await speed.press('End')
}

async function values(page: Page) {
  return (await page.getByTestId('array-values').innerText()).split(', ').map(Number)
}

test('linear search finds the first duplicate and reports missing targets without changing input', async ({ page }) => {
  await prepare(page)
  await page.getByRole('combobox', { name: 'Dataset' }).selectOption('duplicates')
  const original = await values(page)
  const target = original[3]
  await page.getByRole('spinbutton', { name: 'Target value' }).fill(String(target))
  await page.getByRole('button', { name: 'Start searching' }).click()
  await expect(page.locator('.status')).toHaveText('Search complete')
  await expect(page.getByTestId('search-result')).toHaveText(`Found ${target} at position ${original.indexOf(target) + 1}.`)
  expect(await values(page)).toEqual(original)
  await expect(page.getByTestId('writes')).toHaveText('0')
  await page.getByRole('spinbutton', { name: 'Target value' }).fill('101')
  await expect(page.locator('.status')).toHaveText('Ready to search')
  await expect(page.getByTestId('comparisons')).toHaveText('0')
  await page.getByRole('button', { name: 'Start searching' }).click()
  await expect(page.getByTestId('search-result')).toHaveText('101 is not in this array.')
  await expect(page.getByTestId('comparisons')).toHaveText('8')
  expect(await values(page)).toEqual(original)
  const timeline = page.getByRole('slider', { name: /^Timeline/ })
  await timeline.focus(); await timeline.press('Home')
  await expect(page.getByTestId('search-result')).toHaveText('Looking for 101.')
  await expect(page.getByTestId('comparisons')).toHaveText('0')
  await page.getByRole('button', { name: 'Step', exact: true }).click()
  await expect(page.getByTestId('comparisons')).toHaveText('1')
  await expect(page.getByTestId('operation-description')).toContainText('target 101')
})

test('binary search labels its ascending copy, restores source order and resets target safely', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await prepare(page)
  await page.getByRole('combobox', { name: 'Dataset' }).selectOption('reversed')
  const original = await values(page)
  await page.getByRole('combobox', { name: 'Algorithm', exact: true }).selectOption('binary')
  await expect(page.getByTestId('search-input-hint')).toContainText('ascending copy')
  expect(await values(page)).toEqual([...original].sort((a, b) => a - b))
  await page.getByRole('spinbutton', { name: 'Target value' }).fill('10')
  await page.getByRole('button', { name: 'Start searching' }).click()
  await expect(page.getByTestId('search-result')).toHaveText('Found 10 at position 1.')
  await expect(page.locator('.plot-caption')).toContainText('SEARCH FINISHED')
  const timeline = page.getByRole('slider', { name: /^Timeline/ })
  await timeline.focus(); await timeline.press('Home')
  await expect(page.getByTestId('search-result')).toHaveText('Looking for 10.')
  await page.getByRole('button', { name: 'Pick an array value' }).click()
  const target = await page.getByRole('spinbutton', { name: 'Target value' }).inputValue()
  expect(original).toContain(Number(target))
  await expect(page.locator('.status')).toHaveText('Ready to search')
  await page.getByRole('combobox', { name: 'Algorithm', exact: true }).selectOption('linear')
  expect(await values(page)).toEqual(original)
  await page.getByRole('button', { name: 'Sorting', exact: true }).click()
  expect(await values(page)).toEqual(original)
  await expect(page.getByRole('button', { name: 'Start sorting' })).toBeVisible()
  expect(errors).toEqual([])
})

test('invalid target prevents playback, and fractional or out-of-range targets can be absent', async ({ page }) => {
  await prepare(page)
  const target = page.getByRole('spinbutton', { name: 'Target value' })
  await target.fill('')
  await expect(target).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('button', { name: 'Start searching' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Step', exact: true })).toBeDisabled()
  await page.locator('h1').click(); await page.keyboard.press('Space')
  await expect(page.locator('.status')).toHaveText('Ready to search')
  await target.fill('100.5')
  await expect(target).toHaveAttribute('aria-invalid', 'false')
  await page.getByRole('button', { name: 'Start searching' }).click()
  await expect(page.getByTestId('search-result')).toHaveText('100.5 is not in this array.')
  await target.fill('-1')
  await page.getByRole('combobox', { name: 'Algorithm', exact: true }).selectOption('binary')
  await page.getByRole('button', { name: 'Start searching' }).click()
  await expect(page.getByTestId('search-result')).toHaveText('-1 is not in this array.')
})

test('linear and binary comparison share input and target with working result and reverse seeking', async ({ page }) => {
  await prepare(page)
  await page.getByRole('spinbutton', { name: 'Target value' }).fill('100')
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  const left = page.getByTestId('comparison-primary')
  const right = page.getByTestId('comparison-secondary')
  await left.locator('summary').click(); await right.locator('summary').click()
  expect(await left.getByTestId('array-values').innerText()).toEqual(await right.getByTestId('array-values').innerText())
  await expect(page.getByTestId('search-input-hint')).toContainText('both searches use the same sorted copy')
  await page.getByRole('button', { name: 'Start both' }).click()
  await expect(left.locator('.status')).toHaveText('Search complete')
  await expect(right.locator('.status')).toHaveText('Search complete')
  await expect(left.getByTestId('operation-description')).toHaveText('Found 100 at position 8.')
  await expect(right.getByTestId('operation-description')).toHaveText('Found 100 at position 8.')
  await expect(page.locator('.outcome-grid > div').first().locator('strong')).toHaveText('Binary search')
  const timeline = page.getByRole('slider', { name: /^Shared timeline/ })
  await timeline.focus(); await timeline.press('Home')
  await expect(left.getByTestId('comparisons')).toHaveText('0')
  await expect(right.getByTestId('comparisons')).toHaveText('0')
  await expect(left.getByTestId('operation-description')).toHaveText('Looking for 100.')
  await page.getByRole('combobox', { name: 'Right algorithm' }).selectOption('linear')
  await expect(page.getByTestId('search-input-hint')).toContainText('dataset order')
})

