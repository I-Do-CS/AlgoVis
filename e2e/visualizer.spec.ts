import { expect, test } from '@playwright/test'

test('step, play, pause, change speed, complete, replay, and reset', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  const size = page.getByRole('slider', { name: /Array size/ })
  await size.focus()
  await size.press('Home')
  await page.getByText('Inspect array values', { exact: false }).click()
  const original = await page.getByTestId('array-values').innerText()
  expect(original.split(', ')).toHaveLength(8)
  await page.getByRole('button', { name: 'Step', exact: true }).click()
  await expect(page.getByTestId('operations')).toHaveText(/^1 \/ /)
  await page.getByRole('button', { name: 'Step', exact: true }).click()
  await expect(page.getByTestId('comparisons')).toHaveText('1')
  await page.getByRole('button', { name: 'Resume' }).click()
  await expect(page.getByRole('button', { name: 'Step', exact: true })).toBeDisabled()
  await expect(page.getByTestId('operations')).not.toHaveText(/^2 \/ /)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const paused = await page.getByTestId('operations').innerText()
  await page.waitForTimeout(200)
  await expect(page.getByTestId('operations')).toHaveText(paused)
  const speed = page.getByRole('slider', { name: /Speed/ })
  await speed.focus()
  await speed.press('End')
  await expect(speed).toHaveAttribute('aria-valuetext', /8 times/)
  await page.getByRole('button', { name: 'Resume' }).click()
  await expect(page.locator('.status')).toHaveText('Sorted')
  const result = (await page.getByTestId('array-values').innerText()).split(', ').map(Number)
  expect(result).toEqual([...result].sort((a, b) => a - b))
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '100')
  await page.getByRole('button', { name: 'Replay' }).click()
  await expect(page.locator('.status')).toHaveText('Sorting')
  await page.getByRole('button', { name: 'Reset array' }).click()
  await expect(page.getByTestId('array-values')).toHaveText(original)
  await expect(page.getByTestId('comparisons')).toHaveText('0')
  await expect(page.getByTestId('writes')).toHaveText('0')
  await expect(page.locator('.status')).toHaveText('Ready to sort')
  expect(errors).toEqual([])
})

test('shuffle and resize safely replace an active experiment', async ({ page }) => {
  await page.goto('/')
  await page.getByText('Inspect array values', { exact: false }).click()
  const original = await page.getByTestId('array-values').innerText()
  await page.getByRole('button', { name: 'Start sorting' }).click()
  await page.getByRole('button', { name: 'Shuffle array' }).click()
  await expect(page.locator('.status')).toHaveText('Ready to sort')
  await expect(page.getByTestId('array-values')).not.toHaveText(original)
  await page.getByRole('button', { name: 'Start sorting' }).click()
  const size = page.getByRole('slider', { name: /Array size/ })
  await size.focus()
  await size.press('End')
  await expect(page.locator('.status')).toHaveText('Ready to sort')
  expect((await page.getByTestId('array-values').innerText()).split(', ')).toHaveLength(96)
  await expect(page.getByTestId('operations')).toHaveText(/^0 \/ /)
})

test('keyboard controls work with reduced motion and leave sliders usable', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('operations')).toHaveText(/^1 \/ /)
  await page.keyboard.press('r')
  await expect(page.locator('.status')).toHaveText('Ready to sort')
  await page.keyboard.press('Space')
  await expect(page.locator('.status')).toHaveText('Sorting')
  await page.keyboard.press('Space')
  await expect(page.locator('.status')).toHaveText('Paused')
  const speed = page.getByRole('slider', { name: /Speed/ })
  await speed.focus()
  await speed.press('ArrowRight')
  await expect(speed).toHaveValue('3')
  await expect(page.locator('.status')).toHaveText('Paused')
})

test('canvas renders and the layout fits phone, tablet, and desktop screens', async ({ page }) => {
  await page.goto('/')
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1100 })
    await expect(page.getByRole('button', { name: 'Start sorting' })).toBeVisible()
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
    expect(overflow, `Horizontal overflow at ${width}px`).toBe(false)
  }
  await expect.poll(async () => page.locator('canvas').evaluate((canvas: HTMLCanvasElement) => {
    const context = canvas.getContext('2d')!
    const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data
    return pixels.some((value, index) => index % 4 === 3 && value > 0)
  })).toBe(true)
  await page.screenshot({ path: '/tmp/algovis-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.locator('canvas').evaluate((canvas: HTMLCanvasElement) =>
    canvas.width === Math.round(canvas.getBoundingClientRect().width * window.devicePixelRatio),
  )).toBe(true)
  await page.screenshot({ path: '/tmp/algovis-mobile.png', fullPage: true })
})
