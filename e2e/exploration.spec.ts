test('timeline seeking, previous step, and resume restore merge writes and exact counts', async ({ page }) => {
  await page.goto('/')
  await smallArray(page)
  await page.getByRole('combobox', { name: 'Algorithm', exact: true }).selectOption('merge')
  await page.getByRole('combobox', { name: 'Dataset' }).selectOption('reversed')
  await page.getByText('Inspect array values', { exact: false }).click()
  const original = (await page.getByTestId('array-values').innerText()).split(', ').map(Number)
  const timeline = page.getByRole('slider', { name: /^Timeline/ })
  await timeline.focus()
  for (let i = 0; i < 5; i++) await timeline.press('ArrowRight')
  await expect(timeline).toHaveValue('5')
  await expect(page.getByTestId('writes')).toHaveText('1')
  await expect(page.locator('.status')).toHaveText('Paused')
  await page.getByRole('button', { name: 'Previous step' }).click()
  await expect(timeline).toHaveValue('4')
  await expect(page.getByTestId('writes')).toHaveText('0')
  expect((await page.getByTestId('array-values').innerText()).split(', ').map(Number)).toEqual(original)
  await timeline.focus()
  await timeline.press('End')
  await expect(page.locator('.status')).toHaveText('Sorted')
  expect((await page.getByTestId('array-values').innerText()).split(', ').map(Number)).toEqual([...original].sort((a, b) => a - b))
  await timeline.press('Home')
  await expect(page.getByTestId('comparisons')).toHaveText('0')
  await expect(page.locator('.status')).toHaveText('Ready to sort')
  await page.getByRole('button', { name: 'Start sorting' }).click()
  await timeline.focus()
  await timeline.press('End')
  await expect(page.locator('.status')).toHaveText('Sorted')
  await timeline.press('Home')
  await timeline.press('ArrowRight')
  await page.getByRole('button', { name: 'Resume' }).click()
  await expect(page.locator('.status')).toHaveText('Sorted', { timeout: 10_000 })
})

test('shared playback holds a finished side, pauses both, and compares final counts', async ({ page }) => {
  const { left, right } = await openComparison(page)
  await page.getByRole('combobox', { name: 'Left algorithm' }).selectOption('bubble')
  await page.getByRole('combobox', { name: 'Right algorithm' }).selectOption('selection')
  await page.getByRole('combobox', { name: 'Dataset' }).selectOption('sorted')
  expect(await arrayValues(left)).toEqual(await arrayValues(right))
  await page.getByRole('button', { name: 'Start both' }).click()
  await expect(left.locator('.status')).toHaveText('Sorted')
  await expect(right.locator('.status')).toHaveText('Sorting')
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const held = await left.getByTestId('operations').innerText()
  const paused = await right.getByTestId('operations').innerText()
  await page.waitForTimeout(150)
  await expect(right.getByTestId('operations')).toHaveText(paused)
  const speed = page.getByRole('slider', { name: /Speed/ })
  await speed.focus()
  await speed.press('End')
  await page.getByRole('button', { name: 'Resume' }).click()
  await expect(right.locator('.status')).toHaveText('Sorted')
  await expect(left.getByTestId('operations')).toHaveText(held)
  await expect(left.getByTestId('comparisons')).toHaveText('7')
  await expect(right.getByTestId('comparisons')).toHaveText('28')
  await expect(page.locator('.outcome-grid > div').filter({ hasText: 'Fewer comparisons' })).toContainText('Bubble sort')
  await expect(page.locator('.outcome-grid > div').filter({ hasText: 'Fewer array writes' })).toContainText('Tie')
  await page.getByRole('button', { name: 'Replay' }).click()
  await page.getByRole('button', { name: 'Reset array' }).click()
  await expect(left.getByTestId('comparisons')).toHaveText('0')
  await expect(right.getByTestId('comparisons')).toHaveText('0')
})

test('comparison scrub, algorithm changes, shuffle, and mode changes preserve the shared input', async ({ page }) => {
  const { left, right } = await openComparison(page)
  await page.getByRole('combobox', { name: 'Left algorithm' }).selectOption('merge')
  await page.getByRole('combobox', { name: 'Right algorithm' }).selectOption('quick')
  await page.getByRole('combobox', { name: 'Dataset' }).selectOption('reversed')
  const original = await arrayValues(left)
  const timeline = page.getByRole('slider', { name: /Shared timeline/ })
  await timeline.focus()
  for (let i = 0; i < 5; i++) await timeline.press('ArrowRight')
  await expect(left.getByTestId('writes')).toHaveText('1')
  await page.getByRole('combobox', { name: 'Right algorithm' }).selectOption('insertion')
  expect(await arrayValues(left)).toEqual(original)
  expect(await arrayValues(right)).toEqual(original)
  await timeline.focus()
  await timeline.press('End')
  await expect(left.locator('.status')).toHaveText('Sorted')
  await expect(right.locator('.status')).toHaveText('Sorted')
  await timeline.press('Home')
  for (let i = 0; i < 5; i++) await timeline.press('ArrowRight')
  await page.getByRole('button', { name: 'Shuffle array' }).click()
  const shuffled = await arrayValues(left)
  expect([...shuffled].sort((a, b) => a - b)).toEqual([...original].sort((a, b) => a - b))
  expect(await arrayValues(right)).toEqual(shuffled)
  await page.getByRole('combobox', { name: 'Dataset' }).selectOption('duplicates')
  expect(new Set(await arrayValues(left)).size).toBe(5)
  expect(await arrayValues(right)).toEqual(await arrayValues(left))
  await page.getByRole('button', { name: 'Explore', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Algorithm', exact: true })).toHaveValue('merge')
  await expect(page.getByRole('combobox', { name: 'Dataset' })).toHaveValue('duplicates')
  await expect(page.locator('.status')).toHaveText('Ready to sort')
})

test('identical algorithms remain synchronized through shared stepping and speed changes', async ({ page }) => {
  const { left, right } = await openComparison(page)
  await page.getByRole('combobox', { name: 'Left algorithm' }).selectOption('merge')
  await page.getByRole('button', { name: 'Step', exact: true }).click()
  await expect(left.getByTestId('operations')).toHaveText(/^1 \/ /)
  await expect(right.getByTestId('operations')).toHaveText(/^1 \/ /)
  await page.getByRole('button', { name: 'Resume' }).click()
  await expect(left.getByTestId('operations')).not.toHaveText(/^1 \/ /)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  expect(await left.getByTestId('operations').innerText()).toBe(await right.getByTestId('operations').innerText())
  expect(await arrayValues(left)).toEqual(await arrayValues(right))
  const speed = page.getByRole('slider', { name: /Speed/ })
  await speed.focus()
  await speed.press('End')
  await page.getByRole('button', { name: 'Resume' }).click()
  await expect(left.locator('.status')).toHaveText('Sorted')
  await expect(right.locator('.status')).toHaveText('Sorted')
  expect(await left.getByTestId('comparisons').innerText()).toBe(await right.getByTestId('comparisons').innerText())
})

test('comparison is usable on phone, tablet, and desktop with reduced motion', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await page.getByRole('combobox', { name: 'Left algorithm' }).selectOption('quick')
  for (const width of [320, 390, 768, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1100 })
    await expect(page.getByRole('button', { name: 'Start both' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), `Comparison overflows at ${width}px`).toBe(false)
  }
  const timeline = page.getByRole('slider', { name: /Shared timeline/ })
  await timeline.focus()
  for (let i = 0; i < 3; i++) await timeline.press('PageUp')
  await page.getByRole('heading', { level: 1 }).click()
  await page.screenshot({ path: '/tmp/algovis-m3-compare-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.locator('canvas').evaluateAll((canvases) => canvases.every((element) => {
    const canvas = element as HTMLCanvasElement
    return canvas.width === Math.round(canvas.getBoundingClientRect().width * window.devicePixelRatio)
  }))).toBe(true)
  await page.screenshot({ path: '/tmp/algovis-m3-compare-mobile.png', fullPage: true })
  await expect(page.locator('footer')).toContainText('Ali Ghelichkhani')
  expect(errors).toEqual([])
})
