import { expect, test, type Locator, type Page } from '@playwright/test'

async function arrayValues(scope: Locator): Promise<number[]> {
  return (await scope.getByTestId('array-values').innerText()).split(', ').map(Number)
}

async function smallArray(page: Page) {
  const size = page.getByRole('slider', { name: /Array size/ })
  await size.focus()
  await size.press('Home')
}

async function openComparison(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Compare', exact: true }).click()
  await smallArray(page)
  const left = page.getByTestId('comparison-primary')
  const right = page.getByTestId('comparison-secondary')
  await left.getByText('Inspect left array values').click()
  await right.getByText('Inspect right array values').click()
  return { left, right }
}

